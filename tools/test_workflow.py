"""Browser regression for the illustrated walkthrough; no licensed media needed."""
import json
from pathlib import Path
import sys
from playwright.sync_api import sync_playwright

url = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:8794'
output = Path(sys.argv[2] if len(sys.argv) > 2 else 'local/workflow-preview')
output.mkdir(parents=True, exist_ok=True)
checks = []

def ok(name, value):
    assert value, name
    checks.append(name)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, args=['--no-sandbox', '--disable-dev-shm-usage'])
    page = browser.new_page(viewport={'width':1440, 'height':1100}, reduced_motion='reduce')
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.clock.install()
    page.goto(url, wait_until='networkidle')
    page.locator('#method').scroll_into_view_if_needed()
    ok('no autoplay on entry', 'is-playing' not in page.locator('#workflow-demo').get_attribute('class'))
    for route, stages in [('valid', [0,1,4]), ('missing', [2,3,4]), ('mismatch', [0,1,2,3,4])]:
        page.locator(f'button[data-route={route}]').click()
        ok(f'{route}: entry stage', page.locator('#demo-scene').get_attribute('data-stage') == str(stages[0]))
        ok(f'{route}: first previous disabled', page.locator('#demo-prev').is_disabled())
        for index, stage in enumerate(stages):
            page.locator(f'[data-step="{stage}"]').click()
            ok(f'{route}: illustrated stage {stage}', page.locator('#demo-scene').get_attribute('data-stage') == str(stage))
            ok(f'{route}: progress label {stage}', page.locator('#demo-position').inner_text() == f'{index+1} / {len(stages)}')
            ok(f'{route}: scene populated {stage}', len(page.locator('#demo-scene').inner_text()) > 40)
            if stage == 1 and route == 'mismatch':
                expected = 'corrected' if route == 'valid' else 'original'
                ok(f'{route}: actual waveform pair', page.locator(f'.demo-wave[data-panel={expected}]').count() == 1)
                ok(f'{route}: waveform drawn', page.locator('.demo-wave').first.evaluate('c=>c.getContext("2d").getImageData(50,20,1,1).data[3]') == 255)
            if route == 'mismatch':
                page.locator('#workflow-demo').screenshot(path=str(output/f'desktop-stage-{stage}.png'), animations='disabled')
        ok(f'{route}: last next disabled', page.locator('#demo-next').is_disabled())
        page.locator('#demo-prev').click()
        ok(f'{route}: previous follows branch', page.locator('#demo-scene').get_attribute('data-stage') == str(stages[-2]))
        page.locator('#demo-next').click()
        ok(f'{route}: next follows branch', page.locator('#demo-scene').get_attribute('data-stage') == str(stages[-1]))

    ok('default pace is ten seconds', page.locator('#demo-speed').input_value() == '10000')
    page.locator('#demo-speed').select_option('6000')
    page.locator('#demo-reset').click()
    page.locator('#demo-play').click()
    page.clock.run_for(6200)
    ok('play advances to compare', page.locator('#demo-scene').get_attribute('data-stage') == '1')
    page.locator('#demo-play').click()
    page.clock.run_for(6000)
    ok('pause holds current stage', page.locator('#demo-scene').get_attribute('data-stage') == '1')
    ok('pause stops visual motion', 'is-playing' not in page.locator('#workflow-demo').get_attribute('class'))
    page.locator('#demo-play').click()
    page.clock.run_for(25000)
    ok('play reaches final stage', page.locator('#demo-scene').get_attribute('data-stage') == '4')
    ok('play stops at end', 'Complete' in page.locator('#demo-state').inner_text())
    page.locator('#demo-play').click()
    ok('replay restarts', page.locator('#demo-scene').get_attribute('data-stage') == '0')
    page.locator('button[data-route=missing]').click()
    ok('changing route stops playback', 'is-playing' not in page.locator('#workflow-demo').get_attribute('class'))
    ok('missing path skips existing-index checks', page.locator('[data-step="0"]').is_disabled() and page.locator('[data-step="1"]').is_disabled())
    page.locator('#demo-play').click()
    page.clock.run_for(18500)
    ok('missing path completes', 'Complete' in page.locator('#demo-state').inner_text())
    page.locator('button[data-route=valid]').click()
    page.locator('#demo-play').click()
    page.clock.run_for(12500)
    ok('valid path skips search and review', page.locator('#demo-scene').get_attribute('data-stage') == '4')
    page.locator('#demo-play').click()
    page.locator('button[data-route=mismatch]').click()
    page.locator('[data-step="3"]').focus()
    page.keyboard.press('Enter')
    ok('stage buttons keyboard accessible', page.locator('#demo-scene').get_attribute('data-stage') == '3')
    ok('review uses approved boundaries', '18282' in page.locator('#demo-scene').inner_text() and '18350' in page.locator('#demo-scene').inner_text())
    ok('real scenario explicit', page.locator('#scenario-kind').inner_text() == 'Real repair case')
    ok('review shows real corrected waveform', page.locator('.demo-wave[data-panel=corrected]').count() == 1)
    ok('review shows unchanged word waveform', page.locator('.demo-wave[data-panel=word]').count() == 1)
    ok('review labels verified interval', 'Verified interval' in page.locator('#demo-scene').inner_text())
    for route in ['valid', 'missing']:
        page.locator(f'button[data-route={route}]').click()
        ok(f'{route}: labeled schematic', page.locator('#scenario-kind').inner_text() == 'Schematic scenario')
        for button in page.locator('[data-step]:enabled').all():
            button.click()
            text = page.locator('#demo-scene').inner_text()
            ok(f'{route}: no borrowed real sample in stage', 'lawyer' not in text and 'F04' not in text and '18282' not in text)
    page.locator('button[data-route=missing]').click()
    ok('missing route has both direct inputs', page.locator('[data-edge=source-search].on-route').count() == 1 and page.locator('[data-edge=query-search].on-route').count() == 1)
    ok('missing route does not enter index comparison', page.locator('[data-edge=reference].off-route').count() == 1 and page.locator('[data-edge=input].off-route').count() == 1)
    ok('mobile-readable route summary', 'Word audio + video speech → Search' in page.locator('#route-summary').inner_text())
    ok('missing route title does not imply old index', page.locator('#step-title').inner_text() == 'Locate the matching word interval')
    page.locator('#workflow-demo').screenshot(path=str(output/'missing-index-route.png'), animations='disabled')
    page.locator('button[data-route=mismatch]').click()
    page.locator('[data-step="2"]').click()
    ok('search illustration disclosed', 'Schematic waveforms' in page.locator('#demo-scene').inner_text())
    page.locator('#search-result').click()
    ok('candidate before verification', 'Candidate interval' in page.locator('#candidate-outcome').inner_text() and 'Reviewed' not in page.locator('#candidate-outcome').inner_text())
    ok('known candidate source', 'F04 / B3 [18282, 18350)' in page.locator('#candidate-outcome').inner_text())
    page.locator('#demo-scene').screenshot(path=str(output/'candidate-comparison.png'), animations='disabled')
    ok('candidate comparison has same schematic shape', page.locator('#candidate-wave path').get_attribute('d') == page.locator('.candidate-comparison > div').first.locator('path').get_attribute('d'))
    page.locator('#search-offset').evaluate("e=>{e.value='100';e.dispatchEvent(new Event('input',{bubbles:true}));}")
    ok('slider changes candidate waveform', page.locator('#candidate-wave path').get_attribute('d') != page.locator('.candidate-comparison > div').first.locator('path').get_attribute('d'))
    page.locator('#search-offset').focus()
    page.keyboard.press('ArrowRight')
    ok('search slider keyboard accessible', page.locator('#search-offset').input_value() == '101')
    page.locator('#demo-reset').click()
    page.locator('[data-step="2"]').click()
    page.locator('#demo-play').click()
    page.clock.run_for(2000)
    ok('reduced motion does not sweep continuously', page.locator('#search-offset').input_value() == '0')
    page.locator('#demo-play').click()
    page.emulate_media(reduced_motion='no-preference')
    page.clock.run_for(50)
    page.locator('#demo-play').click()
    page.clock.run_for(1000)
    ok('explicit playback moves query-length window', int(page.locator('#search-offset').input_value()) > 0)
    page.locator('#demo-play').click()
    before = page.locator('#search-offset').input_value()
    page.clock.run_for(1000)
    ok('pause freezes candidate position', before == page.locator('#search-offset').input_value())
    page.locator('#demo-speed').select_option('15000')
    ok('speed control preserves progress', before == page.locator('#search-offset').input_value())
    page.emulate_media(reduced_motion='reduce')
    for width in [1440, 768, 390, 320]:
        page.set_viewport_size({'width':width, 'height':1000})
        for stage in range(5):
            page.locator(f'[data-step="{stage}"]').click()
            ok(f'{width}px stage {stage}: no overflow', page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
            if width == 390:
                page.locator('#workflow-demo').screenshot(path=str(output/f'mobile-stage-{stage}.png'), animations='disabled')
    ok('no JavaScript errors', not errors)
    browser.close()
print(json.dumps({'status':'PASS', 'checks':len(checks), 'details':checks, 'screenshots':str(output)}, indent=2))
